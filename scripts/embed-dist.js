import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const distDir = path.resolve(__dirname, '..', 'dist');
const outputFile = path.resolve(__dirname, '..', 'embedded-dist.js');

const MIME_TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'application/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml; charset=utf-8',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.gif': 'image/gif',
  '.ico': 'image/x-icon',
  '.woff': 'font/woff',
  '.woff2': 'font/woff2',
  '.ttf': 'font/ttf',
  '.webp': 'image/webp',
  '.wasm': 'application/wasm'
};

function walkDir(dir, base = '') {
  let results = [];
  if (!fs.existsSync(dir)) return results;
  const list = fs.readdirSync(dir);
  for (const file of list) {
    const fullPath = path.join(dir, file);
    const relPath = path.posix.join(base, file);
    const stat = fs.statSync(fullPath);
    if (stat && stat.isDirectory()) {
      results = results.concat(walkDir(fullPath, relPath));
    } else {
      results.push({ fullPath, relPath: '/' + relPath.replace(/\\/g, '/') });
    }
  }
  return results;
}

const files = walkDir(distDir);
console.log(`Embedding ${files.length} static assets from ${distDir}...`);

const fileMap = {};

for (const f of files) {
  const ext = path.extname(f.fullPath).toLowerCase();
  const mime = MIME_TYPES[ext] || 'application/octet-stream';
  const isBinary = ['.png', '.jpg', '.jpeg', '.gif', '.ico', '.woff', '.woff2', '.ttf', '.webp', '.wasm'].includes(ext);

  if (isBinary) {
    const buffer = fs.readFileSync(f.fullPath);
    fileMap[f.relPath] = {
      type: mime,
      b64: buffer.toString('base64'),
      isBase64: true
    };
  } else {
    const content = fs.readFileSync(f.fullPath, 'utf8');
    fileMap[f.relPath] = {
      type: mime,
      text: content,
      isBase64: false
    };
  }
}

const fileContent = `// Auto-generated by scripts/embed-dist.js. Do not edit manually.
export const EMBEDDED_FILES = ${JSON.stringify(fileMap)};
export default EMBEDDED_FILES;
`;

fs.writeFileSync(outputFile, fileContent, 'utf8');
console.log(`✅ Successfully generated ${outputFile} with ${Object.keys(fileMap).length} embedded assets.`);
